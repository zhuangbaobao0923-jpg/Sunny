enum CallScript {

    /// 接通后的第一句话（电话感，不是聊天开场白；{name} = 用户昵称）
    static func greeting(for character: Character, userName: String) -> String {
        let pool = script(for: character).greetings
        let line = pool.randomElement() ?? "喂，{name}，接通啦？"
        return line.replacingOccurrences(of: "{name}", with: userName)
    }

    /// 冷场碎碎念池（每句都贴角色性格）
    static func chatter(for character: Character) -> [String] {
        script(for: character).chatter
    }

    // MARK: - 分角色话术

    private static func script(for character: Character) -> (greetings: [String], chatter: [String]) {
        if let s = byID[character.id] { return s }
        if let s = byName[character.name] { return s }
        return generic
    }

