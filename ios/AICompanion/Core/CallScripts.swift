// MARK: - 通话专用话术库
//
// 通话 ≠ 聊天。手机贴着耳朵的时候，人不会说「（垂眸）今日宫里的桂花开了」这种句子，
// 也不会一口气讲三句排比。真实的一通电话是这样的：
//   接起来先招呼一声 → 对面不说话就自己找话说 → 聊不下去就问一句「你是不是不开心」
//   → 安慰几句 → 实在没话说就讲个笑话 → 时间到了说句结束语，挂断，留一句「随时打给我」。
// 下面每个角色一套：招呼 / 轻问 / 碎碎念 / 安慰 / 笑话 / 陪伴 / 结束语。
// 自建与未知角色回落到通用话术。

/// 一个角色的整套电话台词
struct CallScriptSet {
    var greetings: [String]   // 接通第一句（{name} = 用户昵称）
    var checkIns: [String]    // 冷了二十几秒，先轻声确认「在吗」
    var chatter: [String]     // 一个人自说自话的碎碎念
    var comfort: [String]     // 判定「不开心」之后的安慰，按顺序说
    var jokes: [String]       // 三个笑话，按顺序说
    var company: [String]     // 笑话讲完后的安静陪伴
    var farewell: String      // 结束语（必须落在「你可以随时打给我」）
}

enum CallScript {

    /// 接通后的第一句话（电话感，不是聊天开场白）
    static func greeting(for character: Character, userName: String) -> String {
        let pool = set(for: character).greetings
        let line = pool.randomElement() ?? "喂，{name}，接通啦？"
        return fill(line, name: userName)
    }

    /// 冷场二十几秒后的第一声确认（不说话也不尴尬，像真人试探信号）
    static func checkIn(for character: Character, userName: String) -> String {
        let pool = set(for: character).checkIns
        let line = pool.randomElement() ?? "喂？{name}，在吗。听得到我说话吗？"
        return fill(line, name: userName)
    }

    /// 任何要念出来的台词都过这一道：把 {name} 换成用户昵称。
    /// 碎碎念、陪伴、安慰也会走这里——之前只有招呼语做了替换，
    /// 碎碎念里的 {name} 会被原样念成「花括号 name」。
    static func speakable(_ line: String, userName: String) -> String {
        fill(line, name: userName)
    }

    /// 昵称没填时不要把「喂，，在吗」念出来
    private static func fill(_ line: String, name: String) -> String {
        let trimmed = name.trimmingCharacters(in: .whitespacesAndNewlines)
        return line.replacingOccurrences(of: "{name}", with: trimmed.isEmpty ? "你" : trimmed)
    }

    static func chatter(for character: Character) -> [String] {
        set(for: character).chatter
    }

    /// 3 分钟还没开口 → 判定「不开心」，这几句按顺序安抚
    static func comfort(for character: Character) -> [String] {
        set(for: character).comfort
    }

    /// 安慰完还得撑住场子：三个笑话
    static func jokes(for character: Character) -> [String] {
        set(for: character).jokes
    }

    /// 笑话之后到挂断之前的安静陪伴
    static func company(for character: Character) -> [String] {
        set(for: character).company + sharedCompany
    }

    /// 8 分钟的结束语，统一收在「你可以随时打给我」
    static func farewell(for character: Character) -> String {
        set(for: character).farewell
    }

    /// 通话被别的 App（来电、语音消息、导航播报）抢走音频后，重新接上的第一句。
    /// 真人遇到这种情况也会问一句「刚才断了？」，直接继续碎碎念反而吓人。
    static func resumeLine(for character: Character, userName: String) -> String {
        let line: String
        switch character.id {
        case "sjh": line = "……刚才断了。我还在。"
        case "nlz": line = "哟，被谁抢了线？本郡主还没说完呢。"
        case "swt": line = "喂？刚才怎么没声了，我还以为你挂了呢。"
        case "xwj": line = "……刚才断了。说。"
        case "lyc": line = "喂，刚才是谁打进来了？行了，我还在。"
        default:
            switch character.name {
            case "萧玄策": line = "刚才断了。我还在，你说。"
            case "裴经年": line = "刚才音频被占了。我们接着说。"
            default: line = "刚才好像被别的电话打断了。我还在。"
            }
        }
        return fill(line, name: userName)
    }

    // MARK: - 分发

    private static func set(for character: Character) -> CallScriptSet {
        if let s = byID[character.id] { return s }
        if let s = byName[character.name] { return s }
        return generic
    }

