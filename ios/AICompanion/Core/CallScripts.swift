// MARK: - 电话模式的本地回复（未配置模型时用）
//
// PersonaEngine 的台词是「文字聊天」的：有括号动作、句子偏长、古风腔重。
// 电话里这些话念出来就不是人说话。这里给一套短、口语、有停顿的接话，
// 情绪类问题优先复用角色的安慰话术，保证「陪着」的感觉不缺席。

enum CallTalk {
    static func reply(for character: Character, history: [ChatMessage], userText: String, level: Int) -> String {
        let text = userText.trimmingCharacters(in: .whitespacesAndNewlines)
        let intent = ChatIntent.classify(text)
        var line: String

        switch intent {
        case .farewell:
            line = "嗯，那你去忙。别关机啊——想说话随时打过来。"
        case .emotional:
            line = CallScript.comfort(for: character).randomElement()
                ?? "我在。你慢慢说，说不出来也没关系。"
        case .praise:
            line = [
                "……你这一句，我记一天。",
                "嗯。（停了停）我也挺喜欢跟你说话的。",
                "别夸了。（笑）再夸我要当真了。"
            ].randomElement()!
        case .question:
            line = [
                "这个我还真说不好。你先讲讲，你怎么想的。",
                "嗯……让我想想。（停了两秒）你先说你的。",
                "问得挺突然。（笑）不过我愿意听你问。"
            ].randomElement()!
        case .greeting:
            line = "嗯，我在。"
        case .invite:
            line = "行啊。什么时候，你说个时间。"
        case .aboutYou:
            line = "我啊……一句两句说不完。你要是想听，我慢慢讲。"
        case .daily:
            line = [
                "嗯，我听着呢。",
                "然后呢。",
                "这事听着就烦人。你接着说。",
                "我今天也在想你那边怎么样了。",
                "别急，慢慢讲。我这边有的是时间。"
            ].randomElement()!
        }

        if ChatText.isUltraShort(text) {
            line = [
                "嗯？（等着）",
                "就一个字啊。行，我等你把话攒够。",
                "嗯，我在听。"
            ].randomElement()!
        }
        // 电话里没有动作描写：模型/台词池里偶尔带的括号内容一律剥掉
        return VoiceService.spokenPart(of: line)
    }
}
